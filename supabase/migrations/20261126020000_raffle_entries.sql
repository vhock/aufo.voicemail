-- Raffle entries (optional, offered after the participant clicks "Finished").
--
-- Stores the email address and the keyed hash of the phone number the
-- participant called from (same public.phone_hash() / Vault key as deletion
-- requests), so entries can be verified against the hashed caller numbers of
-- the recordings. The phone number itself is never stored.
--
-- Requires 20261126010000_hashed_phone_deletion.sql (phone_hash + Vault key).

create table if not exists public.raffle_entries (
    id           bigint generated by default as identity primary key,
    email        text not null,
    phone_hash   text not null unique,
    ui_language  text,
    entered_at   timestamptz not null default now()
);

comment on table public.raffle_entries is
    'Raffle entries: email + HMAC-SHA256 of the caller number. Delete all rows once the raffle is over.';

alter table public.raffle_entries
    drop constraint if exists raffle_entries_email_check,
    add  constraint raffle_entries_email_check
         check (char_length(email) between 3 and 254 and email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$');

alter table public.raffle_entries
    drop constraint if exists raffle_entries_phone_hash_check,
    add  constraint raffle_entries_phone_hash_check
         check (phone_hash ~ '^[0-9a-f]{64}$');

alter table public.raffle_entries
    drop constraint if exists raffle_entries_ui_language_check,
    add  constraint raffle_entries_ui_language_check
         check (ui_language is null or char_length(ui_language) <= 8);

-- RLS on, no policies: only reachable through the RPC below.
alter table public.raffle_entries enable row level security;
revoke all on table public.raffle_entries from anon, authenticated;

-- Called by the website. Returns { status: 'entered' | 'already' | 'invalid_input' }.
-- One entry per phone number; a second entry with the same number is rejected
-- (it does not overwrite the email of the first one).
create or replace function public.enter_raffle(
    p_email       text,
    p_phone       text,
    p_ui_language text default null
)
returns json
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_email text := lower(btrim(coalesce(p_email, '')));
    v_phone text := btrim(coalesce(p_phone, ''));
begin
    if v_phone !~ '^\+[1-9][0-9]{7,14}$'
       or char_length(v_email) not between 3 and 254
       or v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
        return json_build_object('status', 'invalid_input');
    end if;

    insert into public.raffle_entries (email, phone_hash, ui_language)
    values (v_email, public.phone_hash(v_phone), left(p_ui_language, 8))
    on conflict (phone_hash) do nothing;

    if found then
        return json_build_object('status', 'entered');
    end if;
    return json_build_object('status', 'already');
end;
$$;

revoke all on function public.enter_raffle(text, text, text) from public;
grant execute on function public.enter_raffle(text, text, text) to anon;
