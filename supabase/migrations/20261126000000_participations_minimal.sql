-- Minimal-data participation (DSGVO data minimisation, privacy policy v2).
--
-- Participation now only requires the phone model. No email, no phone
-- number and no participant ID are collected. Each click on "Participate"
-- inserts one row into public.participations.
--
-- The legacy public.participants table and its RPCs are left untouched so
-- existing rows can still be processed/purged; the website no longer uses them.

create table if not exists public.participations (
    id              bigint generated by default as identity primary key,
    phone_model     text not null,
    ui_language     text,
    consent_version text not null,
    consented_at    timestamptz not null default now()
);

comment on table public.participations is
    'One row per participation submitted from the website. Contains no identifying data (phone model + consent record only).';
comment on column public.participations.consent_version is
    'Version identifier of the privacy policy / consent text the participant agreed to (e.g. v2-2026-11-26).';
comment on column public.participations.consented_at is
    'Server-side timestamp of consent (Art. 7 (1) GDPR proof of consent). Not settable by anon.';

-- Hard limits to discourage abuse since anon can insert
alter table public.participations
    drop constraint if exists participations_phone_model_length_check,
    add  constraint participations_phone_model_length_check
         check (char_length(btrim(phone_model)) between 1 and 128);

alter table public.participations
    drop constraint if exists participations_ui_language_check,
    add  constraint participations_ui_language_check
         check (ui_language is null or char_length(ui_language) <= 8);

alter table public.participations
    drop constraint if exists participations_consent_version_check,
    add  constraint participations_consent_version_check
         check (char_length(btrim(consent_version)) between 1 and 32);

alter table public.participations enable row level security;

drop policy if exists "anon can insert participations" on public.participations;
create policy "anon can insert participations"
    on public.participations
    for insert
    to anon
    with check (true);

-- Column-level privileges: anon may only supply these three columns, so
-- consented_at always comes from the server clock. No select/update/delete.
revoke all on table public.participations from anon, authenticated;
grant insert (phone_model, ui_language, consent_version)
    on table public.participations to anon;
